// Run a synchronous set of SQLite writes together. BEGIN IMMEDIATE acquires the write lock before
// work reads or changes rows.

export function transaction(db, work) {
  db.exec("BEGIN IMMEDIATE");
  try {
    const result = work();
    db.exec("COMMIT");
    return result;
  } catch (error) {
    db.exec("ROLLBACK");
    throw error;
  }
}
